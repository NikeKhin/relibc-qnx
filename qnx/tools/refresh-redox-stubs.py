#!/usr/bin/env python3
"""Regenerates the stand-ins for relibc's Redox-only git dependencies.

relibc's Cargo.lock pins some crates as git dependencies on
gitlab.redox-os.org that only Redox compiles. Cargo resolves the whole
lockfile on every target, so a QNX or Linux build would fetch them anyway,
and that route can stall. `qnx/tools/cargo-redox-stubs.toml` points those git
sources at `qnx/tools/redox-git-stubs`, which holds, for each crate, its manifest
at the locked revision without any code: the same name, version, features
and dependencies, so the lockfile resolves unchanged. A crate that Redox code
checked here compiles (redox_syscall, which redox-rt uses) is copied whole
instead, from the same revision.

    refresh-redox-stubs.py            # regenerate stand-ins and config from Cargo.lock
    refresh-redox-stubs.py --check    # fail if any stand-in is stale

For each crate it fetches only the locked commit, without file contents
(`git fetch --depth 1 --filter=blob:none`), and then just the one
`Cargo.toml` it needs, or for a copied crate just its directory: a few
kilobytes, or about a hundred, even on a slow route. Needs python3 and git.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
# The relibc root: this file is in its qnx/tools/ directory.
TREE = os.path.normpath(os.path.join(HERE, "..", ".."))
STUBS = os.path.join(HERE, "redox-git-stubs")
CONFIG = os.path.join(HERE, "cargo-redox-stubs.toml")

# Git dependencies that only Redox compiles. Anything else from git is a real
# dependency of every target and is left for Cargo to fetch.
REDOX_ONLY = {"redox-buffer-pool", "redox-rings", "redox_syscall"}

# Of those, the ones copied whole, because redox-rt — which check-redox.sh
# checks with the stand-ins in place — compiles them.
COPIED = {"redox_syscall"}

# Manifest tables a stand-in keeps; everything else only matters for building
# or publishing the real crate.
KEEP_TABLES = re.compile(r"^(package|lib|features|dependencies|build-dependencies|"
                         r"target\..*\.(dependencies|build-dependencies))$")
KEEP_PACKAGE = {"name", "version", "edition", "license", "links"}

CONFIG_HEADER = """\
# relibc's Cargo.lock pins Redox-only crates as git dependencies on
# gitlab.redox-os.org. Builds for other targets never use them, but Cargo
# resolves the whole lockfile and so fetches them anyway, which stalls on a
# slow route to that server. This replaces those git sources with stand-ins
# in qnx/tools/redox-git-stubs that declare the same features and dependencies,
# so the lockfile resolves unchanged and nothing is fetched from GitLab.
#
# The port's scripts pass this file with --config. redox_syscall is a full
# copy, since redox-rt, which check-redox.sh checks, compiles it; the others
# carry no code, so a build of relibc itself for Redox must not use this.
#
# Cargo reads the `directory` below relative to qnx/, the parent of this
# file's directory.
#
# Generated by qnx/tools/refresh-redox-stubs.py from Cargo.lock; do not edit.
"""


def locked_git_packages():
    with open(os.path.join(TREE, "Cargo.lock")) as f:
        lock = f.read()
    out = []
    for block in lock.split("[[package]]"):
        name = re.search(r'^name = "([^"]+)"', block, re.M)
        version = re.search(r'^version = "([^"]+)"', block, re.M)
        source = re.search(r'^source = "git\+([^"#]+)#([0-9a-f]+)"', block, re.M)
        if name and version and source:
            url, _, query = source.group(1).partition("?")
            out.append({"name": name.group(1), "version": version.group(1),
                        "url": url, "query": query, "rev": source.group(2)})
    return out


def stub_manifest(text, pkg):
    """The parts of a real manifest that resolution depends on."""
    out, table = [], None
    for line in text.splitlines():
        header = re.match(r"^\[([^\[\]]+)\]\s*(#.*)?$", line)
        if header:
            table = header.group(1).strip()
            if KEEP_TABLES.match(table):
                out.append("")
                out.append(line)
            continue
        if re.match(r"^\[\[", line):
            table = None
            continue
        if table is None or not KEEP_TABLES.match(table):
            continue
        if table == "package":
            key = line.split("=")[0].strip()
            if key in KEEP_PACKAGE:
                out.append(line)
        elif table == "lib":
            key = line.split("=")[0].strip()
            if key == "name":
                out.append(line)
        else:
            out.append(line)
    head = (f"# Stand-in for {pkg['name']} at {pkg['rev']}, from\n"
            f"# {pkg['url']}: the same name, version, features and\n"
            "# dependencies, and no code. Generated by qnx/tools/refresh-redox-stubs.py.\n")
    return head + re.sub(r"\n{3,}", "\n\n", "\n".join(out).strip()) + "\n"


def fetch(pkg, dest=None):
    """The package's manifest at its locked revision; with `dest`, also a
    copy of its whole directory there."""
    with tempfile.TemporaryDirectory() as repo:
        def git(*args):
            return subprocess.run(["git", "-C", repo, *args], capture_output=True,
                                  text=True, check=True, timeout=600).stdout
        subprocess.run(["git", "init", "-q", repo], check=True)
        git("fetch", "-q", "--depth", "1", "--filter=blob:none", pkg["url"], pkg["rev"])
        for path in git("ls-tree", "-r", "--name-only", "FETCH_HEAD").splitlines():
            if path == "Cargo.toml" or path.endswith("/Cargo.toml"):
                text = git("show", f"FETCH_HEAD:{path}")
                if re.search(rf'^name\s*=\s*"{re.escape(pkg["name"])}"', text, re.M):
                    break
        else:
            sys.exit(f"{pkg['name']}: no Cargo.toml for it in {pkg['url']} at {pkg['rev']}")
        if dest is not None:
            crate = os.path.dirname(path)
            # A sparse checkout of the one directory fetches its files in a
            # single request.
            git("sparse-checkout", "set", "--no-cone", f"/{crate}/" if crate else "/*")
            git("checkout", "-q", "FETCH_HEAD")
            shutil.copytree(os.path.join(repo, crate), dest,
                            ignore=shutil.ignore_patterns(".git", ".gitignore"))
        return text


def recorded_rev(name):
    try:
        with open(os.path.join(STUBS, name, "Cargo.toml")) as f:
            m = re.search(r"(?:Stand-in for|Copy of) \S+ at ([0-9a-f]+)", f.readline())
            return m.group(1) if m else None
    except FileNotFoundError:
        return None


def config_text(pkgs):
    out = [CONFIG_HEADER]
    seen = set()
    for pkg in pkgs:
        key = (pkg["url"], pkg["query"])
        if key in seen:
            continue
        seen.add(key)
        label = re.sub(r"[^A-Za-z0-9]+", "-", pkg["url"].split("://", 1)[-1]).strip("-")
        out.append(f"[source.{label}]")
        out.append(f'git = "{pkg["url"]}"')
        for part in filter(None, pkg["query"].split("&")):
            k, _, v = part.partition("=")
            out.append(f'{k} = "{v}"')
        out.append('replace-with = "redox-git-stubs"\n')
    out.append("[source.redox-git-stubs]")
    out.append('directory = "tools/redox-git-stubs"')
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="fail if a stand-in is stale")
    args = ap.parse_args()

    pkgs = locked_git_packages()
    stubbed = [p for p in pkgs if p["name"] in REDOX_ONLY]
    others = [p for p in pkgs if p["name"] not in REDOX_ONLY]
    for p in others:
        print(f"git dependency fetched as usual: {p['name']} {p['version']} ({p['url']})")
    stale = [p for p in stubbed if recorded_rev(p["name"]) != p["rev"]]
    present = {d for d in os.listdir(STUBS) if os.path.isdir(os.path.join(STUBS, d))}
    extra = present - {p["name"] for p in stubbed}
    config_ok = os.path.isfile(CONFIG) and open(CONFIG).read() == config_text(stubbed)

    if args.check:
        for p in stale:
            print(f"stale: {p['name']} stand-in is not for the locked {p['rev'][:12]}")
        for name in sorted(extra):
            print(f"stale: {name} has a stand-in but is no longer locked from git")
        if not config_ok:
            print("stale: qnx/tools/cargo-redox-stubs.toml does not match Cargo.lock")
        if stale or extra or not config_ok:
            print("run qnx/tools/refresh-redox-stubs.py")
            return 1
        print(f"stand-ins match Cargo.lock: {', '.join(p['name'] for p in stubbed)}")
        return 0

    for p in stale:
        d = os.path.join(STUBS, p["name"])
        shutil.rmtree(d, ignore_errors=True)
        if p["name"] in COPIED:
            print(f"fetching {p['name']} at {p['rev'][:12]} from {p['url']}")
            manifest = fetch(p, d)
            with open(os.path.join(d, "Cargo.toml"), "w") as f:
                f.write(f"# Copy of {p['name']} at {p['rev']}, from\n# {p['url']}; "
                        "generated by qnx/tools/refresh-redox-stubs.py.\n" + manifest)
        else:
            print(f"fetching {p['name']} manifest at {p['rev'][:12]} from {p['url']}")
            manifest = stub_manifest(fetch(p), p)
            os.makedirs(os.path.join(d, "src"), exist_ok=True)
            with open(os.path.join(d, "Cargo.toml"), "w") as f:
                f.write(manifest)
            with open(os.path.join(d, "src", "lib.rs"), "w") as f:
                f.write(f"//! Manifest-only stand-in for {p['name']}; never used outside Redox.\n"
                        "#![no_std]\n")
        with open(os.path.join(d, ".cargo-checksum.json"), "w") as f:
            json.dump({"files": {}, "package": None}, f)
            f.write("\n")
    for name in sorted(extra):
        shutil.rmtree(os.path.join(STUBS, name))
        print(f"removed the stand-in for {name}")
    with open(CONFIG, "w") as f:
        f.write(config_text(stubbed))
    print(f"stand-ins match Cargo.lock: {', '.join(p['name'] for p in stubbed)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
